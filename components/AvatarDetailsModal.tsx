import React from 'react';
import { Modal } from './Modal';
import { Avatar } from '../types';
import { Button } from './Button';

interface AvatarDetailsModalProps {
  isOpen: boolean;
  onClose: () => void;
  avatar: Avatar | null;
}

export const AvatarDetailsModal: React.FC<AvatarDetailsModalProps> = ({ isOpen, onClose, avatar }) => {
  if (!avatar) return null;

  const downloadImage = () => {
    const link = document.createElement('a');
    link.href = avatar.imageData;
    link.download = `nano-banana-${avatar.id.slice(0, 8)}.png`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const formatDate = (timestamp: number) => {
    return new Date(timestamp).toLocaleString(undefined, {
      dateStyle: 'medium',
      timeStyle: 'short',
    });
  };

  return (
    <Modal isOpen={isOpen} onClose={onClose} title="Avatar Details">
      <div className="flex flex-col md:flex-row h-full">
        {/* Image Section */}
        <div className="md:w-1/2 bg-black/50 flex items-center justify-center p-6 border-b md:border-b-0 md:border-r border-slate-800">
          <img 
            src={avatar.imageData} 
            alt={avatar.prompt} 
            className="max-w-full max-h-[60vh] object-contain rounded-lg shadow-2xl border border-slate-800"
          />
        </div>

        {/* Metadata Section */}
        <div className="md:w-1/2 p-6 flex flex-col gap-6 bg-slate-900">
          
          {/* Prompt */}
          <div>
            <h3 className="text-xs font-bold uppercase tracking-wider text-slate-500 mb-2">Prompt / Instruction</h3>
            <div className="bg-slate-950 rounded-lg p-4 border border-slate-800 max-h-40 overflow-y-auto custom-scrollbar">
              <p className="text-slate-300 text-sm leading-relaxed">{avatar.prompt}</p>
            </div>
          </div>

          {/* Info Grid */}
          <div className="grid grid-cols-2 gap-4">
            <div>
              <h3 className="text-xs font-bold uppercase tracking-wider text-slate-500 mb-1">Created</h3>
              <p className="text-white font-mono text-sm">{formatDate(avatar.createdAt)}</p>
            </div>
            <div>
              <h3 className="text-xs font-bold uppercase tracking-wider text-slate-500 mb-1">ID</h3>
              <p className="text-white font-mono text-xs truncate" title={avatar.id}>{avatar.id}</p>
            </div>
            {avatar.parentId && (
              <div className="col-span-2">
                <h3 className="text-xs font-bold uppercase tracking-wider text-slate-500 mb-1">Lineage</h3>
                <p className="text-indigo-400 text-sm flex items-center gap-1">
                  <span className="text-lg">↳</span> Derived from previous iteration
                </p>
              </div>
            )}
          </div>

          <div className="mt-auto pt-6 border-t border-slate-800 flex flex-col gap-3">
            <Button onClick={downloadImage} className="w-full justify-center">
              <svg className="w-5 h-5 mr-2" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M4 16v1a3 3 0 003 3h10a3 3 0 003-3v-1m-4-4l-4 4m0 0l-4-4m4 4V4" />
              </svg>
              Save Image to Device
            </Button>
            <div className="text-center">
              <p className="text-xs text-slate-600">
                This image is generated by Gemini 2.5 Flash Image.
              </p>
            </div>
          </div>
        </div>
      </div>
    </Modal>
  );
};