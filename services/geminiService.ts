
import { GoogleGenAI } from "@google/genai";
import { GEMINI_MODEL } from "../constants";

// Initialize the client
const ai = new GoogleGenAI({ apiKey: process.env.API_KEY });

/**
 * Extracts the base64 image data from the Gemini response parts.
 */
function extractImageFromResponse(response: any): string | null {
  if (!response.candidates || response.candidates.length === 0) return null;
  
  const parts = response.candidates[0].content?.parts || [];
  for (const part of parts) {
    if (part.inlineData && part.inlineData.data) {
      return `data:${part.inlineData.mimeType || 'image/png'};base64,${part.inlineData.data}`;
    }
  }
  return null;
}

/**
 * Helper to extract mime type from base64 string
 */
function getMimeType(base64String: string): string {
  const match = base64String.match(/^data:(image\/[a-zA-Z+]+);base64,/);
  return match ? match[1] : 'image/png';
}

/**
 * Retry wrapper for API calls with exponential backoff to handle transient network errors.
 */
async function withRetry<T>(operation: () => Promise<T>, retries = 3, delay = 2000): Promise<T> {
  let lastError: any;
  
  for (let i = 0; i < retries; i++) {
    try {
      return await operation();
    } catch (error: any) {
      lastError = error;
      // Check for network/XHR errors (code 6) or server errors (5xx)
      const isNetworkError = error.message?.includes('xhr') || 
                             error.message?.includes('fetch') || 
                             error.message?.includes('network') ||
                             error.message?.includes('Rpc failed');
      const isServerError = error.status && error.status >= 500;
      
      // Explicitly check for Rate Limiting (429 / RESOURCE_EXHAUSTED)
      const isRateLimit = error.status === 429 || 
                          (error.message && (
                            error.message.includes('429') || 
                            error.message.includes('RESOURCE_EXHAUSTED') ||
                            error.message.includes('Too Many Requests')
                          ));
      
      if (isNetworkError || isServerError || isRateLimit) {
        // If rate limited, use a more aggressive initial delay (minimum 5s)
        const currentDelay = isRateLimit ? Math.max(delay, 5000) : delay;
        
        console.warn(`Gemini API attempt ${i + 1} failed. Retrying in ${currentDelay}ms...`, error.message);
        await new Promise(resolve => setTimeout(resolve, currentDelay));
        
        // Exponential backoff
        delay *= 2; 
        continue;
      }
      
      // If it's a non-retriable error (like 400 Bad Request), throw immediately
      throw error;
    }
  }
  throw lastError;
}

/**
 * Generates a new avatar based on a text prompt and optional reference image.
 */
export async function generateAvatarImage(prompt: string, referenceImage?: string): Promise<string> {
  return withRetry(async () => {
    try {
      const parts: any[] = [{ text: prompt }];

      // If a reference image is provided, add it to the parts (multimodal input)
      if (referenceImage) {
        const mimeType = getMimeType(referenceImage);
        // Strip prefix to get raw base64
        const cleanBase64 = referenceImage.replace(/^data:image\/(png|jpeg|jpg|webp);base64,/, '');
        
        parts.unshift({
          inlineData: {
            data: cleanBase64,
            mimeType: mimeType, 
          },
        });
      }

      const response = await ai.models.generateContent({
        model: GEMINI_MODEL,
        contents: {
          parts: parts
        },
      });

      const imageUrl = extractImageFromResponse(response);
      if (!imageUrl) {
        throw new Error("No image generated by the model. The prompt might have been blocked or the model failed.");
      }
      return imageUrl;
    } catch (error) {
      console.error("Error generating avatar:", error);
      throw error;
    }
  });
}

/**
 * Edits an existing avatar based on an image and a text prompt (instruction).
 */
export async function editAvatarImage(base64Image: string, instruction: string): Promise<string> {
  // 1. Detect proper MIME type from the existing data URI
  const mimeType = getMimeType(base64Image);
  
  // 2. Strip the data URI prefix to get raw base64
  const cleanBase64 = base64Image.replace(/^data:image\/(png|jpeg|jpg|webp);base64,/, '');

  return withRetry(async () => {
    try {
      const response = await ai.models.generateContent({
        model: GEMINI_MODEL,
        contents: {
          parts: [
            {
              inlineData: {
                data: cleanBase64,
                mimeType: mimeType, 
              },
            },
            {
              text: instruction,
            },
          ],
        },
      });

      const imageUrl = extractImageFromResponse(response);
      if (!imageUrl) {
        throw new Error("No edited image generated by the model.");
      }
      return imageUrl;
    } catch (error) {
      console.error("Error editing avatar:", error);
      throw error;
    }
  });
}
